import {
  ASCENT_CAMPAIGN,
  rarityOf,
  DEFAULT_DECK_SLOTS_PER_CHAMPION,
  defaultCampaignHero,
  GUEST_ENCOUNTER_LIMIT,
  isChampionUnlocked,
  revalidateChampionProgress,
  createProfile,
  isCardForHero,
  isNeutral,
  parseProfileSave,
  parseRunSave,
  reofferPending,
  starterDeck,
  starterHeroProfile,
  starterShared,
  isLegacyDeck,
  validateDeck,
  type DeckRules,
  type GameContent,
  type HeroProfile,
  type PlayerProfile,
  type RunState,
  type SharedCollection,
} from '../../src/game';

export interface ImportResult {
  profile: PlayerProfile;
  /** Every champion's valid campaign run. */
  runs: RunState[];
  /** The Mage run, if any. */
  run: RunState | null;
  /** What was dropped or corrected (reported to the client, never silently). */
  notes: string[];
  /** Client totals above the legacy allowance need provenance before ANY import is saved. */
  unverifiedCopies: { ownerId: string; cardId: string; claimed: number; allowance: number }[];
}

/** Frozen legacy migration allowance, NOT derived from current deck rules. Unverified
 * client totals above this allowance cannot authorize grants to a connected account. */
const LEGACY_IMPORT_ALLOWANCE = { COMMON: 3, UNCOMMON: 2, RARE: 1, LEGENDARY: 1, ULTRA: 1 } as const;
const importAllowance = (card: Parameters<typeof rarityOf>[0]) => LEGACY_IMPORT_ALLOWANCE[rarityOf(card)];

const DECK_ID = /^[a-z0-9_-]{1,32}$/;

/**
 * One-time migration of a device's local progress. Local data is untrusted: it goes through
 * the same parsers as a local load, then the server tightens it —
 * - collection: only cards of that champion; copies bounded by the frozen legacy import allowance, independent of deck rules, never below the starter set; neutral cards only in the shared
 *   pool, under the same cap;
 * - decks: must be legal with the imported collection, otherwise the starter deck;
 * - campaign: one save per champion; each must be a valid run of THAT champion; a pending
 *   reward offer is regenerated by the server.
 * - pity: never imported (a local counter would let a save force drops); starts at 0.
 * - champions: a save from before unlocks (no `champions`) stays LEGACY (open roster, the
 *   backfill policy). A newer save is rebuilt through the unlock rules: the starting choice
 *   must be `available`, each later unlock must be justified by the imported progress. A guest
 *   could never pass encounter III, so a newer save claiming more is capped there, and its runs
 *   past that point (or of champions it does not own) are dropped.
 */
export function sanitizeLocalImport(
  rawProfile: unknown,
  /** Raw campaign save per champion id (a bare string = the Mage's, as older clients send). */
  rawRuns: unknown,
  content: GameContent,
  rules: DeckRules,
  /** Champions released to the importing account (see the Worker's `availableChampions`). */
  available: readonly string[] = Object.keys(content.heroes),
): ImportResult {
  const notes: string[] = [];
  const unverifiedCopies: ImportResult['unverifiedCopies'] = [];
  let profile = createProfile(content);
  if (typeof rawProfile === 'string' && rawProfile) {
    const parsed = parseProfileSave(rawProfile, content);
    if (parsed.status === 'OK') {
      notes.push(...parsed.notes);
      profile = parsed.profile;
    } else if (parsed.status === 'INVALID') notes.push(`profile discarded: ${parsed.reason}`);
  }

  const starterPool = starterShared(content).collection;
  const shared: SharedCollection = { collection: {}, acquisitions: 0 };
  for (const [cardId, owned] of Object.entries(profile.shared?.collection ?? {})) {
    const card = content.cards[cardId];
    if (!card || !isNeutral(card)) continue;
    const copies = Math.max(starterPool[cardId]?.copies ?? 0, Math.min(owned.copies, importAllowance(card)));
    if (copies < owned.copies) unverifiedCopies.push({ownerId:'*',cardId,claimed:owned.copies,allowance:copies});
    if (copies < owned.copies) notes.push(`shared: ${cardId} unverified surplus not imported; legacy allowance ${copies} copies`);
    if (copies > 0) shared.collection[cardId] = { copies, acquired: Math.max(0, Math.floor(owned.acquired)) };
  }
  for (const [cardId, owned] of Object.entries(starterPool)) shared.collection[cardId] ??= { ...owned };
  shared.acquisitions = Object.values(shared.collection).reduce((n, c) => Math.max(n, c.acquired), 0);

  const heroes: Record<string, HeroProfile> = {};
  for (const hero of Object.values(content.heroes)) {
    const local = profile.heroes[hero.id] ?? starterHeroProfile(hero, content);
    const starter = starterHeroProfile(hero, content).collection;
    const collection: HeroProfile['collection'] = {};
    for (const [cardId, owned] of Object.entries(local.collection)) {
      const card = content.cards[cardId];
      if (!card || !isCardForHero(card, hero.id) || isNeutral(card)) continue;
      // Exclusive cards (world rewards) are only granted by the server's own source.
      if (card.acquisition) {
        if (owned.copies > (starter[cardId]?.copies ?? 0)) unverifiedCopies.push({ownerId:hero.id,cardId,claimed:owned.copies,allowance:starter[cardId]?.copies ?? 0});
        notes.push(`${hero.id}: ${cardId} not imported (exclusive reward)`);
        continue;
      }
      const floor = starter[cardId]?.copies ?? 0;
      const copies = Math.max(floor, Math.min(owned.copies, importAllowance(card)));
      if (copies < owned.copies) unverifiedCopies.push({ownerId:hero.id,cardId,claimed:owned.copies,allowance:copies});
      if (copies < owned.copies) notes.push(`${hero.id}: ${cardId} unverified surplus not imported; legacy allowance ${copies} copies`);
      if (copies > 0) collection[cardId] = { copies, acquired: Math.max(0, Math.floor(owned.acquired)) };
    }
    for (const [cardId, owned] of Object.entries(starter)) collection[cardId] ??= { ...owned };
    const owns = (cardId: string) => (collection[cardId] ?? shared.collection[cardId])?.copies ?? 0;

    // At most the slot limit per champion; the device's default deck is always among them.
    const kept = local.decks.filter((d, i) => DECK_ID.test(d.id) && local.decks.findIndex((o) => o.id === d.id) === i);
    const active = kept.find((d) => d.id === local.activeDeckId);
    const chosen = new Set([...new Set([...(active ? [active] : []), ...kept])].slice(0, DEFAULT_DECK_SLOTS_PER_CHAMPION));
    const capped = kept.filter((d) => chosen.has(d));
    if (capped.length < kept.length) notes.push(`${hero.id}: kept ${capped.length} of ${kept.length} decks (limit ${DEFAULT_DECK_SLOTS_PER_CHAMPION})`);
    const decks = capped
      .map((d) => {
        const issues = validateDeck(d.cards, hero.id, owns, content, rules);
        // A LEGACY (old-size, otherwise legal) deck is imported exactly as it is: the player completes it.
        const legal = issues.length === 0 || isLegacyDeck(d.cards, issues, rules);
        if (!legal) notes.push(`${hero.id}: deck "${d.id}" was not legal; starter deck used`);
        return { id: d.id, name: d.name.slice(0, 40) || 'Mazo', cards: legal ? d.cards.map((e) => ({ ...e })) : starterDeck(hero) };
      });
    const base = starterHeroProfile(hero, content);
    heroes[hero.id] = {
      heroId: hero.id,
      collection,
      acquisitions: Object.values(collection).reduce((n, c) => Math.max(n, c.acquired), 0),
      decks: decks.length ? decks : base.decks,
      activeDeckId: decks.some((d) => d.id === local.activeDeckId) ? local.activeDeckId : (decks[0]?.id ?? base.activeDeckId),
      rewardPity: 0,
    };
  }

  let sanitized: PlayerProfile = { heroes, shared, selectedChampionId: profile.selectedChampionId };
  const saves: Record<string, unknown> =
    typeof rawRuns === 'object' && rawRuns !== null && !Array.isArray(rawRuns)
      ? (rawRuns as Record<string, unknown>)
      : { [defaultCampaignHero(ASCENT_CAMPAIGN)]: rawRuns };
  const progression = profile.champions?.mode === 'PROGRESSION';
  const parsedRuns: RunState[] = [];
  for (const heroId of ASCENT_CAMPAIGN.heroIds) {
    const raw = saves[heroId];
    if (typeof raw !== 'string' || !raw) continue;
    const parsed = parseRunSave(raw, ASCENT_CAMPAIGN, content);
    if (parsed.status === 'OK' && parsed.run.heroId !== heroId) notes.push(`${heroId}: campaign discarded: it is a ${parsed.run.heroId} run`);
    else if (parsed.status === 'OK' && progression && parsed.run.completedEncounterIds.length > GUEST_ENCOUNTER_LIMIT)
      notes.push(`${heroId}: campaign discarded: a guest cannot pass encounter ${GUEST_ENCOUNTER_LIMIT}`);
    else if (parsed.status === 'OK') parsedRuns.push(parsed.run);
    else if (parsed.status === 'INVALID') notes.push(`${heroId}: campaign discarded: ${parsed.reason}`);
  }
  if (profile.champions) {
    const best = Math.max(profile.champions.campaignBest, ...parsedRuns.map((r) => r.completedEncounterIds.length));
    const champions = revalidateChampionProgress(
      profile.champions,
      sanitized,
      available,
      progression ? Math.min(best, GUEST_ENCOUNTER_LIMIT) : best,
      notes,
    );
    sanitized = { ...sanitized, ...(champions.mode === 'PROGRESSION' ? { champions } : {}) };
    // The selection must be a champion the account owns (the starting one otherwise).
    if (!isChampionUnlocked(sanitized, sanitized.selectedChampionId) && champions.startingChampionId)
      sanitized = { ...sanitized, selectedChampionId: champions.startingChampionId };
  }
  const runs: RunState[] = [];
  for (const run of parsedRuns) {
    if (!isChampionUnlocked(sanitized, run.heroId)) {
      notes.push(`${run.heroId}: campaign discarded: champion not unlocked`);
      continue;
    }
    // Never trust a stored offer: the server rolls the one this collection would really get.
    runs.push(reofferPending(ASCENT_CAMPAIGN, content, sanitized, run, rules));
  }
  const run = runs.find((r) => r.heroId === defaultCampaignHero(ASCENT_CAMPAIGN)) ?? null;
  return { profile: sanitized, runs, run, notes, unverifiedCopies };
}
